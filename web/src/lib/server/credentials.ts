/**
 * The dashboard's own password, hashed and checked in-process.
 *
 * The hash lives in the environment (`STREAMKIT_DASHBOARD_PASSWORD_HASH`), not in
 * an htpasswd file. That removes the two things the file required: the `htpasswd`
 * binary to create the first hash, and a path that only exists on the production
 * host. A fresh checkout sets one variable and is done.
 *
 * bcrypt is implemented here with `bcryptjs` rather than by shelling out, so the
 * password never leaves this process — not on a command line, which `ps` shows to
 * every user on the box, and not down a pipe. `bcryptjs` reads every bcrypt
 * prefix (`$2a$`, `$2b$`, `$2y$`), so a hash generated by any tool is one this
 * checks.
 *
 * The hash is read per call, never captured at import: the change-password route
 * updates `process.env` after it writes the new value, and a captured constant
 * would keep checking the old hash until a restart.
 *
 * No `server-only` import: this module is pure bcrypt over an environment
 * variable, and the test suite runs it under plain `node` — which cannot resolve
 * the `server-only` shim. The route that calls it is the one that carries the
 * server-only guarantee.
 */

import bcrypt from 'bcryptjs'

/** The variable the hash lives in. */
const KEY = 'STREAMKIT_DASHBOARD_PASSWORD_HASH'

/** What a check against the stored hash concluded. */
export type VerifyResult = 'ok' | 'wrong' | 'no-user'

/**
 * The cost factor. Ten is the usual default and matches the hashes this replaces;
 * it is stated rather than left to a library default so it cannot drift.
 */
export const COST = 10

/** A bcrypt hash, in any of the prefixes bcrypt uses. Anything else — an MD5
 *  `$apr1$` hash from an older file, or a plaintext password pasted in by
 *  mistake — cannot be checked, and saying so is better than a "wrong password"
 *  the operator cannot act on. */
const BCRYPT = /^\$2[aby]?\$\d{2}\$/

/** Whether `value` looks like a bcrypt hash this module can check. */
export function isBcryptHash(value: string): boolean {
  return BCRYPT.test(value)
}

/**
 * The configured hash, or null if none is set.
 *
 * Null is "no credential configured", which every caller treats as "nobody can
 * sign in" rather than "anyone can" — the same fail-closed rule the backend's
 * token follows.
 */
export function passwordHash(): string | null {
  const hash = (process.env[KEY] ?? '').trim()
  return hash || null
}

/** Whether `password` is the one the configured hash was made from. */
export async function verifyPassword(password: string): Promise<VerifyResult> {
  const stored = passwordHash()
  if (stored === null) return 'no-user'
  if (!BCRYPT.test(stored)) {
    throw new Error('STREAMKIT_DASHBOARD_PASSWORD_HASH is not a bcrypt hash')
  }
  return (await bcrypt.compare(password, stored)) ? 'ok' : 'wrong'
}

/** A bcrypt hash for `password`, at the module's cost factor. */
export function hashPassword(password: string): Promise<string> {
  return bcrypt.hash(password, COST)
}

/**
 * Whether `password` verifies against `hash` specifically.
 *
 * Distinct from `verifyPassword`, which checks the hash in force. This is the
 * check a freshly generated hash is put through before it is saved: it proves the
 * new hash is sound while the old one is still the one in force, so a failure
 * cannot lock anyone out.
 */
export function passwordMatchesHash(password: string, hash: string): Promise<boolean> {
  return bcrypt.compare(password, hash)
}
